/*
 * Ihtiyat alert and explainable emergency-action engine.
 *
 * This migration introduces the relational foundation for:
 *
 * - backend-managed bilingual alerts;
 * - location applicability for alerts;
 * - reusable bilingual emergency safety actions;
 * - deterministic, inspectable action-ranking rules;
 * - optional preparedness-task linkage;
 * - limited household-aware rule conditions.
 *
 * Alerts and action rules are curated public safety catalogue data.
 * Anonymous and authenticated application clients may read only content that
 * is suitable for publication. Ordinary application roles cannot create,
 * modify or delete that content.
 *
 * Severity is an internal Ihtiyat scenario value from 1 to 3. It supports
 * deterministic simulation and testing and is not presented as an
 * independently issued official warning classification.
*/

begin;


/* -------------------------------------------------------------------------
 * 1. ALERTS
 * -------------------------------------------------------------------------
 *
 * Alerts describe simulated or backend-managed hazard events independently
 * of their affected locations.
 *
 * Location applicability is stored separately in alert_locations so one
 * alert may apply to several curated Saudi locations without duplicating the
 * bilingual alert content.
 *
 * A published alert remains readable after its expires_at timestamp. The
 * mobile application decides whether it belongs in the active or recent
 * section of the feed. This allows alert history without weakening RLS.
*/

create table public.alerts (
	id bigint
		generated by default as identity
		primary key,

	code text
		not null
		unique,

	hazard_id bigint
		not null
		references public.hazards(id)
		on delete restrict,

	origin_type text
		not null,

	external_alert_id text,

	severity smallint
		not null,

	title_en text
		not null,

	title_ar text
		not null,

	message_en text
		not null,

	message_ar text
		not null,

	starts_at timestamptz
		not null,

	published_at timestamptz,

	expires_at timestamptz
		not null,

	publication_status text
		not null
		default 'draft',

	sort_order smallint
		not null
		default 0,

	created_at timestamptz
		not null
		default now(),

	updated_at timestamptz
		not null
		default now(),

	constraint alerts_code_format
		check (
			code ~ '^[a-z0-9]+(_[a-z0-9]+)*$'
		),

	constraint alerts_origin_type_valid
		check (
			origin_type in (
				'simulated',
				'ihtiyat_managed',
				'official_external'
			)
		),

	constraint alerts_severity_valid
		check (
			severity between 1 and 3
		),

	constraint alerts_publication_status_valid
		check (
			publication_status in (
				'draft',
				'published',
				'retired'
			)
		),

	constraint alerts_time_window_valid
		check (
			expires_at > starts_at
		),

	constraint alerts_published_at_state
		check (
			(
				publication_status = 'draft'
				and published_at is null
			)
			or (
				publication_status in (
					'published',
					'retired'
				)
				and published_at is not null
			)
		),

	constraint alerts_sort_order_non_negative
		check (
			sort_order >= 0
		),

	constraint alerts_title_en_length
		check (
			char_length(
				btrim(title_en)
			) between 1 and 180
		),

	constraint alerts_title_ar_length
		check (
			char_length(
				btrim(title_ar)
			) between 1 and 180
		),

	constraint alerts_message_en_length
		check (
			char_length(
				btrim(message_en)
			) between 1 and 3000
		),

	constraint alerts_message_ar_length
		check (
			char_length(
				btrim(message_ar)
			) between 1 and 3000
		),

	constraint alerts_external_id_length
		check (
			external_alert_id is null
			or char_length(
				btrim(external_alert_id)
			) between 1 and 300
		)
);


/* -------------------------------------------------------------------------
 * 2. ALERT-LOCATION APPLICABILITY
 * -------------------------------------------------------------------------
 *
 * A row links one alert to one affected curated location.
 *
 * An alert with no alert_locations rows may later be interpreted by the
 * application as national-scope content. This avoids manufacturing duplicate
 * rows merely to cover the whole location catalogue.
*/

create table public.alert_locations (
	alert_id bigint
		not null
		references public.alerts(id)
		on delete cascade,

	location_id bigint
		not null
		references public.locations(id)
		on delete restrict,

	primary key (
		alert_id,
		location_id
	)
);


/* -------------------------------------------------------------------------
 * 3. REUSABLE SAFETY ACTIONS
 * -------------------------------------------------------------------------
 *
 * Actions contain user-facing bilingual emergency instructions.
 *
 * Hazard, severity, location and preparedness conditions belong to
 * action_rules rather than the action itself. This allows a reusable action
 * such as following official directions to participate in several different
 * hazard scenarios without duplicating its wording.
*/

create table public.actions (
	id bigint
		generated by default as identity
		primary key,

	code text
		not null
		unique,

	title_en text
		not null,

	title_ar text
		not null,

	instruction_en text
		not null,

	instruction_ar text
		not null,

	sort_order smallint
		not null
		default 0,

	is_active boolean
		not null
		default true,

	created_at timestamptz
		not null
		default now(),

	updated_at timestamptz
		not null
		default now(),

	constraint actions_code_format
		check (
			code ~ '^[a-z0-9]+(_[a-z0-9]+)*$'
		),

	constraint actions_sort_order_non_negative
		check (
			sort_order >= 0
		),

	constraint actions_title_en_length
		check (
			char_length(
				btrim(title_en)
			) between 1 and 180
		),

	constraint actions_title_ar_length
		check (
			char_length(
				btrim(title_ar)
			) between 1 and 180
		),

	constraint actions_instruction_en_length
		check (
			char_length(
				btrim(instruction_en)
			) between 1 and 2500
		),

	constraint actions_instruction_ar_length
		check (
			char_length(
				btrim(instruction_ar)
			) between 1 and 2500
		)
);


/* -------------------------------------------------------------------------
 * 4. DETERMINISTIC ACTION RULES
 * -------------------------------------------------------------------------
 *
 * Each rule explains when and how one safety action participates in an action
 * plan.
 *
 * The application later evaluates these rows deterministically:
 *
 * score =
 *     base_priority
 *     + (10 * current_severity)
 *     + incomplete_task_boost
 *     + applicable safety_override
 *
 * Rules below min_severity are excluded.
 *
 * A linked preparedness action is excluded once its linked task has been
 * completed. While unfinished, its configured incomplete_task_boost may
 * contribute to the ranking.
 *
 * Household-aware rules are deliberately limited to children and older
 * adults in V1 because these can be supported with reviewed health/safety
 * guidance. Missing profile data must be treated by the application as
 * unknown rather (null) than as zero.
*/

create table public.action_rules (
	id bigint
		generated by default as identity
		primary key,

	code text
		not null
		unique,

	action_id bigint
		not null
		references public.actions(id)
		on delete cascade,

	hazard_id bigint
		not null
		references public.hazards(id)
		on delete restrict,

	location_id bigint
		references public.locations(id)
		on delete restrict,

	linked_task_id bigint
		references public.mission_tasks(id)
		on delete restrict,

	min_severity smallint
		not null
		default 1,

	base_priority integer
		not null
		default 0,

	incomplete_task_boost integer
		not null
		default 0,

	safety_override integer
		not null
		default 0,

	safety_override_min_severity smallint,

	min_children_count smallint,

	min_older_adults_count smallint,

	reason_en text
		not null,

	reason_ar text
		not null,

	sort_order smallint
		not null
		default 0,

	is_active boolean
		not null
		default true,

	created_at timestamptz
		not null
		default now(),

	updated_at timestamptz
		not null
		default now(),

	constraint action_rules_code_format
		check (
			code ~ '^[a-z0-9]+(_[a-z0-9]+)*$'
		),

	constraint action_rules_min_severity_valid
		check (
			min_severity between 1 and 3
		),

	constraint action_rules_base_priority_non_negative
		check (
			base_priority >= 0
		),

	constraint action_rules_incomplete_task_boost_non_negative
		check (
			incomplete_task_boost >= 0
		),

	constraint action_rules_safety_override_non_negative
		check (
			safety_override >= 0
		),

	constraint action_rules_override_min_severity_valid
		check (
			safety_override_min_severity is null
			or safety_override_min_severity between 1 and 3
		),

	constraint action_rules_children_threshold_valid
		check (
			min_children_count is null
			or min_children_count between 1 and 25
		),

	constraint action_rules_older_adults_threshold_valid
		check (
			min_older_adults_count is null
			or min_older_adults_count between 1 and 25
		),

	constraint action_rules_sort_order_non_negative
		check (
			sort_order >= 0
		),

	constraint action_rules_reason_en_length
		check (
			char_length(
				btrim(reason_en)
			) between 1 and 1500
		),

	constraint action_rules_reason_ar_length
		check (
			char_length(
				btrim(reason_ar)
			) between 1 and 1500
		),

	/*
	 * An incomplete-task boost is meaningful only when the rule actually
	 * references a preparedness task.
	*/
	constraint action_rules_task_boost_requires_task
		check (
			linked_task_id is not null
			or incomplete_task_boost = 0
		),

	/*
	 * Safety overrides are explicit rather than hidden magic constants.
	 * A positive override therefore also records the severity at which that
	 * override becomes applicable.
	*/
	constraint action_rules_override_threshold_consistent
		check (
			(
				safety_override = 0
				and safety_override_min_severity is null
			)
			or (
				safety_override > 0
				and safety_override_min_severity is not null
			)
		)
);


/* -------------------------------------------------------------------------
 * 5. DATABASE-CONTROLLED UPDATED_AT
* ------------------------------------------------------------------------- */

create trigger on_alert_updated
	before update
	on public.alerts
	for each row
	execute function private.set_updated_at();


create trigger on_action_updated
	before update
	on public.actions
	for each row
	execute function private.set_updated_at();


create trigger on_action_rule_updated
	before update
	on public.action_rules
	for each row
	execute function private.set_updated_at();


