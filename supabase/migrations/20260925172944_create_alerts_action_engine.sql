	enable row level security;


/* -------------------------------------------------------------------------
 * 8. CLIENT AND SERVICE-ROLE PRIVILEGES
 * -------------------------------------------------------------------------
 *
 * Alerts and emergency guidance are public safety content.
 *
 * Guests and authenticated users may read curated visible rows but remain
 * unable to mutate them. Catalogue management remains a trusted backend
 * responsibility.
*/

revoke all
	on table
		public.alerts,
		public.alert_locations,
		public.actions,
		public.action_rules
	from anon, authenticated;


grant select
	on table
		public.alerts,
		public.alert_locations,
		public.actions,
		public.action_rules
	to anon, authenticated;


grant select, insert, update, delete
	on table
		public.alerts,
		public.alert_locations,
		public.actions,
		public.action_rules
	to service_role;


/*
 * Ordinary clients never create curated catalogue rows directly, so they do
 * not require access to the identity sequences.
 */

revoke all
	on sequence
		public.alerts_id_seq,
		public.actions_id_seq,
		public.action_rules_id_seq
	from anon, authenticated;


grant usage, select
	on sequence
		public.alerts_id_seq,
		public.actions_id_seq,
		public.action_rules_id_seq
	to service_role;


/* -------------------------------------------------------------------------
 * 9. PUBLIC READ POLICIES
* ------------------------------------------------------------------------- */


/*
 * Alerts are visible only after publication and only while their referenced
 * hazard remains active.
 *
 * Expiry is intentionally not part of the RLS policy. The application needs
 * access to expired published rows for its Recent Alerts section.
*/
create policy "Application clients can read published alerts"
	on public.alerts
	for select
	to anon, authenticated
	using (
		publication_status = 'published'
		and exists (
			select 1
			from public.hazards as hazard
			where hazard.id = hazard_id
				and hazard.is_active
		)
	);


/*
 * Relationship rows are public only when both the parent alert and target
 * location are themselves suitable for application use.
*/
create policy "Application clients can read public alert locations"
	on public.alert_locations
	for select
	to anon, authenticated
	using (
		exists (
			select 1
			from public.alerts as alert
			join public.hazards as hazard
				on hazard.id = alert.hazard_id
			where alert.id = alert_id
				and alert.publication_status = 'published'
				and hazard.is_active
		)
		and exists (
			select 1
			from public.locations as location
			where location.id = location_id
				and location.is_active
		)
	);


/*
 * Reusable actions remain visible only while active.
*/
create policy "Application clients can read active safety actions"
	on public.actions
	for select
	to anon, authenticated
	using (
		is_active
	);


/*
 * A rule is visible only while all catalogue objects needed to evaluate it
 * remain valid.
 *
 * No private user state is consulted here. Task completion and household
 * values are supplied later to the client-side deterministic evaluator.
*/
create policy "Application clients can read active action rules"
	on public.action_rules
	for select
	to anon, authenticated
	using (
		is_active

		and exists (
			select 1
			from public.actions as action
			where action.id = action_id
				and action.is_active
		)

		and exists (
			select 1
			from public.hazards as hazard
			where hazard.id = hazard_id
				and hazard.is_active
		)

		and (
			location_id is null
			or exists (
				select 1
				from public.locations as location
				where location.id = location_id
					and location.is_active
			)
		)

		and (
			linked_task_id is null
			or exists (
				select 1
				from public.mission_tasks as task
				join public.preparedness_missions as mission
					on mission.id = task.mission_id
				left join public.hazards as task_hazard
					on task_hazard.id = task.hazard_id
				where task.id = linked_task_id
					and task.is_active
					and mission.is_active
					and (
						task.hazard_id is null
						or task_hazard.is_active
					)
			)
		)
	);


/* -------------------------------------------------------------------------
 * 10. SCHEMA DOCUMENTATION
* ------------------------------------------------------------------------- */

comment on column public.alerts.severity is
	'Ihtiyat deterministic scenario severity from 1 to 3. It is not an independently issued official warning classification.';


comment on column public.alerts.origin_type is
	'Alert provenance: simulated, Ihtiyat-managed, or an authorised future external source. Simulated alerts must be labelled clearly in the client.';


comment on column public.action_rules.base_priority is
	'Author-set deterministic ranking priority. It is not a statistical probability or scientific risk score.';


comment on column public.action_rules.incomplete_task_boost is
	'Additional deterministic score applied while linked_task_id remains incomplete. The current final-project model uses task completion as a preparedness-state input.';


comment on column public.action_rules.safety_override is
	'Explicit author-set safety priority applied when current severity reaches safety_override_min_severity.';


comment on column public.action_rules.min_children_count is
	'Optional household-aware condition. NULL means this rule does not depend on the number of children. Missing user household data is handled as unknown by the application evaluator.';


comment on column public.action_rules.min_older_adults_count is
	'Optional household-aware condition. NULL means this rule does not depend on older-adult count. Missing user household data is handled as unknown by the application evaluator.';


commit;