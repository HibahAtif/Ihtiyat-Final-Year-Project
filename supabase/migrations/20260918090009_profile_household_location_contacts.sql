/* --------------------------------------------------------------------------
 * Personal emergency contacts
 * --------------------------------------------------------------------------
 *
 * Personal emergency contacts are private user-owned records.
 *
 * They are intentionally separate from Ihtiyat's curated public emergency
 * services. A personal contact is supplied by the user and must never be
 * presented as verified official safety information.
 *
 * Phone numbers are stored in one canonical Saudi E.164-style form.
 * Formatting entered by the user is normalised in the application before
 * insertion.
 */

create table public.personal_emergency_contacts (
	id uuid primary key default gen_random_uuid(),

	user_id uuid not null
		references auth.users(id)
		on delete cascade,

	name text not null,

	relationship_label text not null,

	phone_number text not null,

	email text,

	is_primary boolean not null default false,

	created_at timestamptz not null default now(),

	updated_at timestamptz not null default now(),

	constraint personal_emergency_contacts_name
		check (
			char_length(trim(name)) between 1 and 80
			and name = trim(name)
		),

	constraint personal_emergency_contacts_relationship
		check (
			char_length(trim(relationship_label)) between 1 and 60
			and relationship_label = trim(relationship_label)
		),

	/*
	 * Canonical Saudi subscriber number.
	 *
	 * Accepted stored forms include Saudi geographic fixed-line and mobile
	 * subscriber numbers using country code +966.
	 *
	 * Official short emergency/service codes belong in Ihtiyat's separate
	 * curated emergency-services data and are not personal contacts.
	 */
	constraint personal_emergency_contacts_saudi_phone
		check (
			phone_number ~
			'^\+966(1[123467][0-9]{7}|5[013456789][0-9]{7})$'
		),

	/*
	 * Email is optional. The client performs user-friendly syntax
	 * validation before submission. This database constraint deliberately
	 * remains lightweight rather than attempting to reproduce the complete
	 * Internet email-address specification.
	 */
	constraint personal_emergency_contacts_email
		check (
			email is null
			or (
				char_length(email) between 3 and 254
				and email = trim(email)
				and email ~*
					'^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
			)
		)
);

/*
 * Each account may mark at most one personal emergency contact as primary.
 *
 * Multiple contacts are allowed, but only one row per user can satisfy
 * is_primary = true.
 */
create unique index personal_emergency_contacts_one_primary_per_user
	on public.personal_emergency_contacts (user_id)
	where is_primary = true;

