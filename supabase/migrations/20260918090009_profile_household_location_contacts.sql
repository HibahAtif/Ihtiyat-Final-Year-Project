/* --------------------------------------------------------------------------
 * Saudi administrative location catalogue
 * --------------------------------------------------------------------------
 *
 * Ihtiyat's implemented and evaluated geographic scope is Saudi Arabia.
 *
 * Locations are therefore stored as a curated hierarchy of Saudi
 * administrative areas rather than as a global geographic database.
 *
 * id is Ihtiyat's stable relational identifier.
 *
 * official_code stores the current identifier published by the Saudi
 * National Center for Archives and Records (NCAR) Unified Coding Guide for
 * Administrative Regions, Governorates and Administrative Centres.
 *
 * Other Ihtiyat tables reference locations.id rather than official_code.
 * This isolates application relationships from any future change to the
 * externally maintained administrative coding scheme.
 *
 * Geoapify is not the source of truth for this table. Device coordinates may
 * later be reverse-geocoded through Geoapify and matched to one of these
 * curated rows. Unsupported results must not create locations automatically.
 */

create table public.locations (
	id bigint generated by default as identity primary key,

	parent_id bigint
		references public.locations(id)
		on delete restrict,

	/*
	 * NCAR administrative codes contain leading zeroes, so they are stored
	 * as text rather than numeric values.
	 */
	official_code text not null unique,

	location_type text not null,

	name_en text not null,
	name_ar text not null,

	is_active boolean not null default true,

	created_at timestamptz not null default now(),

	constraint locations_official_code_format
		check (
			official_code ~ '^[0-9]{4}$'
		),

	constraint locations_type
		check (
			location_type in (
				'region',
				'emirate_headquarters',
				'governorate',
				'administrative_centre'
			)
		),

	constraint locations_name_en
		check (
			char_length(trim(name_en)) between 1 and 120
			and name_en = trim(name_en)
		),

	constraint locations_name_ar
		check (
			char_length(trim(name_ar)) between 1 and 120
			and name_ar = trim(name_ar)
		),

	constraint locations_not_own_parent
		check (
			parent_id is null
			or parent_id <> id
		),

    /*
    * Regions form the top level of Ihtiyat's Saudi administrative hierarchy.
    * All more-granular administrative locations must have a parent.
    */
    constraint locations_parent_requirement
        check (
            (
                location_type = 'region'
                and parent_id is null
            )
            or
            (
                location_type <> 'region'
                and parent_id is not null
            )
        )
);



