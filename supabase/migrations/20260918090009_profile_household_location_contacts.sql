/* --------------------------------------------------------------------------
 * Extend authenticated user profiles
 * --------------------------------------------------------------------------
 *
 * The existing profiles table remains the one-to-one application record for
 * an authenticated Supabase user.
 *
 * Day 03 adds only account-level preparedness context that is required by
 * later Ihtiyat features:
 *
 * - one active curated Saudi location;
 * - one preferred supported language;
 * - one implemented app-level text-size preference;
 * - optional household composition counts.
 *
 * Household information is deliberately limited to counts. Ihtiyat does not
 * store names, dates of birth, medical conditions or other individual
 * household-member records.
 */

alter table public.profiles

	add column active_location_id bigint
		references public.locations(id)
		on delete restrict,

	add column preferred_language_code text
		references public.supported_languages(code)
		on delete restrict,

	add column text_size_preference text
		not null
		default 'system',

	add column children_count smallint,

	add column adults_count smallint,

	add column older_adults_count smallint,

	add column pets_count smallint;


alter table public.profiles

	add constraint profiles_text_size_preference
		check (
			text_size_preference in (
				'system',
				'large'
			)
		),

	/*
	 * Each supplied household count must remain within the application's
	 * deliberate input-sanity range.
	 *
	 * NULL means that household information has not been supplied.
	 * Zero means that the user explicitly supplied a count of none.
	 */
	add constraint profiles_children_count_range
		check (
			children_count is null
			or children_count between 0 and 25
		),

	add constraint profiles_adults_count_range
		check (
			adults_count is null
			or adults_count between 0 and 25
		),

	add constraint profiles_older_adults_count_range
		check (
			older_adults_count is null
			or older_adults_count between 0 and 25
		),

	add constraint profiles_pets_count_range
		check (
			pets_count is null
			or pets_count between 0 and 25
		),

	/*
	 * Household data has two valid states:
	 *
	 * 1. all values are NULL:
	 *    the user has not completed household information;
	 *
	 * 2. all values are present:
	 *    the user has explicitly supplied the household composition.
	 *
	 * This avoids ambiguous partial records where NULL could otherwise mean
	 * either "zero" or "not answered".
	 */
	add constraint profiles_household_completion_state
		check (
			(
				children_count is null
				and adults_count is null
				and older_adults_count is null
				and pets_count is null
			)
			or
			(
				children_count is not null
				and adults_count is not null
				and older_adults_count is not null
				and pets_count is not null
			)
		),

	/*
	 * Human household size is derived rather than stored separately.
	 *
	 * Once household information has been completed, at least one human must
	 * be represented and the combined human household size may not exceed 25.
	 *
	 * Pets are deliberately excluded from this human-household total.
	 */
	add constraint profiles_human_household_size
		check (
			children_count is null
			or (
				children_count
				+ adults_count
				+ older_adults_count
			) between 1 and 25
		);

