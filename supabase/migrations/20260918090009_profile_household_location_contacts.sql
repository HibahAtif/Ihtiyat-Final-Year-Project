/* --------------------------------------------------------------------------
 * Generic database-controlled updated_at helper
 * -------------------------------------------------------------------------- */

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
	new.updated_at = now();

	return new;
end;
$$;


create trigger on_personal_emergency_contact_updated
	before update on public.personal_emergency_contacts
	for each row
	execute function private.set_updated_at();

/* --------------------------------------------------------------------------
 * Curated reference-data access control
 * --------------------------------------------------------------------------
 *
 * Supported languages and locations are public configuration data.
 *
 * Guests and authenticated users may read them so that safety-related
 * location/language setup does not require an account.
 *
 * Normal client roles cannot create, alter or delete curated configuration.
 * Authorised backend/service operations retain management access.
 */

alter table public.supported_languages
	enable row level security;

alter table public.locations
	enable row level security;


revoke all
	on table public.supported_languages
	from anon, authenticated;

revoke all
	on table public.locations
	from anon, authenticated;


grant select
	on table public.supported_languages
	to anon, authenticated;

grant select
	on table public.locations
	to anon, authenticated;


grant select, insert, update, delete
	on table public.supported_languages
	to service_role;

grant select, insert, update, delete
	on table public.locations
	to service_role;


/*
 * These tables contain non-sensitive curated configuration.
 *
 * is_active controls application selection/availability rather than acting as
 * a security boundary, so historical/inactive reference rows remain readable.
 */
create policy "Guests and authenticated users can read supported language configuration"
	on public.supported_languages
	for select
	to anon, authenticated
	using (true);


create policy "Guests and authenticated users can read Saudi location configuration"
	on public.locations
	for select
	to anon, authenticated
	using (true);

