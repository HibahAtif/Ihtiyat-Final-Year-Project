/* --------------------------------------------------------------------------
 * Supported application languages
 * --------------------------------------------------------------------------
 *
 * Languages are modelled as reference data rather than hard-coded profile
 * values. This keeps the profile schema extensible if Ihtiyat supports
 * additional languages in the future.
 *
 * Adding a row here does not itself translate the application. A new language
 * would still require translation resources, font/script support and UI
 * testing in the mobile client.
 */

create table public.supported_languages (
	code text primary key,
	name_en text not null,
	native_name text not null,
	layout_direction text not null,
	is_active boolean not null default true,
	created_at timestamptz not null default now(),

	constraint supported_languages_code_format
		check (
			char_length(code) between 2 and 35
			and code = lower(code)
			and code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
		),

	constraint supported_languages_name_en
		check (
			char_length(trim(name_en)) between 1 and 80
			and name_en = trim(name_en)
		),

	constraint supported_languages_native_name
		check (
			char_length(trim(native_name)) between 1 and 80
			and native_name = trim(native_name)
		),

	constraint supported_languages_layout_direction
		check (
			layout_direction in ('ltr', 'rtl')
		)
);


