/*
 * Ihtiyat Resource Hub foundation.
 *
 * This migration introduces a curated, bilingual safety-resource model that
 * can be reused by:
 *
 * - the standalone Resource Hub;
 * - preparedness mission learning tasks;
 * - scenario-quiz explanations;
 * - location/hazard-aware content selection;
 * - a later offline SQLite resource cache;
 * - future alert/action-plan links without duplicating safety guidance.
 *
 * Resource content remains server-curated. Anonymous and authenticated
 * application clients may read only published resources and their active
 * public relationships. Ordinary application roles cannot create, modify or
 * delete curated safety content.
 */

begin;


/* -------------------------------------------------------------------------
 * 1. RESOURCE TOPICS
 * -------------------------------------------------------------------------
 *
 * Topics provide user-facing Resource Hub groupings such as first aid,
 * emergency preparedness and hazard safety.
 *
 * A separate reference table is used instead of a fixed CHECK enum so new
 * topics can be added later without changing the database schema.
 */

create table public.resource_topics (
	id bigint
		generated by default as identity
		primary key,

	code text
		not null
		unique,

	name_en text
		not null,

	name_ar text
		not null,

	description_en text,

	description_ar text,

	sort_order smallint
		not null
		default 0,

	is_active boolean
		not null
		default true,

	created_at timestamptz
		not null
		default now(),

	updated_at timestamptz
		not null
		default now(),

	constraint resource_topics_code_format
		check (
			code ~ '^[a-z0-9]+(_[a-z0-9]+)*$'
		),

	constraint resource_topics_name_en_length
		check (
			char_length(
				btrim(name_en)
			) between 1 and 120
		),

	constraint resource_topics_name_ar_length
		check (
			char_length(
				btrim(name_ar)
			) between 1 and 120
		),

	constraint resource_topics_description_en_length
		check (
			description_en is null
			or char_length(
				btrim(description_en)
			) between 1 and 1000
		),

	constraint resource_topics_description_ar_length
		check (
			description_ar is null
			or char_length(
				btrim(description_ar)
			) between 1 and 1000
		),

	constraint resource_topics_sort_order_non_negative
		check (
			sort_order >= 0
		)
);


/* -------------------------------------------------------------------------
 * 2. CURATED SAFETY RESOURCES
 * -------------------------------------------------------------------------
 *
 * safety_resources stores Ihtiyat's own concise, reviewed bilingual guidance.
 *
 * External official pages are supporting evidence, not the only copy of the
 * safety information. This allows essential guidance to be cached locally
 * later for offline resilience.
 *
 * publication_status separates editorial lifecycle from client visibility:
 *
 * - draft: being prepared/reviewed, never exposed to app clients;
 * - published: approved for application use;
 * - retired: preserved for audit/history, not exposed to app clients.
 */

create table public.safety_resources (
	id bigint
		generated by default as identity
		primary key,

	code text
		not null
		unique,

	title_en text
		not null,

	title_ar text
		not null,

	summary_en text
		not null,

	summary_ar text
		not null,

	content_en text
		not null,

	content_ar text
		not null,

	publication_status text
		not null
		default 'draft',

	sort_order smallint
		not null
		default 0,

	last_reviewed_on date,

	published_at timestamptz,

	created_at timestamptz
		not null
		default now(),

	updated_at timestamptz
		not null
		default now(),

	constraint safety_resources_code_format
		check (
			code ~ '^[a-z0-9]+(_[a-z0-9]+)*$'
		),

	constraint safety_resources_title_en_length
		check (
			char_length(
				btrim(title_en)
			) between 1 and 180
		),

	constraint safety_resources_title_ar_length
		check (
			char_length(
				btrim(title_ar)
			) between 1 and 180
		),

	constraint safety_resources_summary_en_length
		check (
			char_length(
				btrim(summary_en)
			) between 1 and 1000
		),

	constraint safety_resources_summary_ar_length
		check (
			char_length(
				btrim(summary_ar)
			) between 1 and 1000
		),

	constraint safety_resources_content_en_length
		check (
			char_length(
				btrim(content_en)
			) between 1 and 30000
		),

	constraint safety_resources_content_ar_length
		check (
			char_length(
				btrim(content_ar)
			) between 1 and 30000
		),

	constraint safety_resources_publication_status_valid
		check (
			publication_status in (
				'draft',
				'published',
				'retired'
			)
		),

	constraint safety_resources_sort_order_non_negative
		check (
			sort_order >= 0
		),

	constraint safety_resources_published_metadata_present
		check (
			publication_status <> 'published'
			or (
				last_reviewed_on is not null
				and published_at is not null
			)
		)
);


/* -------------------------------------------------------------------------
 * 3. RESOURCE SOURCES
 * -------------------------------------------------------------------------
 *
 * A resource may cite multiple external sources.
 *
 * Source metadata is kept separately from Ihtiyat's own guidance so the same
 * resource can be reviewed against several official/academic references
 * without embedding URLs or publisher details in the article body.
 *
 * source_language_code is NULL for a bilingual or language-independent page.
 */

create table public.resource_sources (
	id bigint
		generated by default as identity
		primary key,

	resource_id bigint
		not null
		references public.safety_resources(id)
		on delete cascade,

	publisher_name_en text
		not null,

	publisher_name_ar text
		not null,

	source_title_en text,

	source_title_ar text,

	source_url text
		not null,

	source_language_code text
		references public.supported_languages(code)
		on delete restrict,

	is_official boolean
		not null
		default false,

	last_checked_on date
		not null,

	sort_order smallint
		not null
		default 0,

	is_active boolean
		not null
		default true,

	created_at timestamptz
		not null
		default now(),

	updated_at timestamptz
		not null
		default now(),

	constraint resource_sources_publisher_name_en_length
		check (
			char_length(
				btrim(publisher_name_en)
			) between 1 and 180
		),

	constraint resource_sources_publisher_name_ar_length
		check (
			char_length(
				btrim(publisher_name_ar)
			) between 1 and 180
		),

	constraint resource_sources_source_title_present
		check (
			source_title_en is not null
			or source_title_ar is not null
		),

	constraint resource_sources_source_title_en_length
		check (
			source_title_en is null
			or char_length(
				btrim(source_title_en)
			) between 1 and 300
		),

	constraint resource_sources_source_title_ar_length
		check (
			source_title_ar is null
			or char_length(
				btrim(source_title_ar)
			) between 1 and 300
		),

	constraint resource_sources_source_url_valid
		check (
			char_length(
				btrim(source_url)
			) between 8 and 2000
			and source_url = btrim(source_url)
			and source_url ~ '^https://[^[:space:]]+$'
		),

	constraint resource_sources_sort_order_non_negative
		check (
			sort_order >= 0
		),

	constraint resource_sources_resource_url_unique
		unique (
			resource_id,
			source_url
		)
);


/* -------------------------------------------------------------------------
 * 4. RESOURCE TOPIC RELATIONSHIPS
 * -------------------------------------------------------------------------
 *
 * A resource can appear under more than one Resource Hub topic.
 *
 * is_primary gives the UI one canonical grouping while preserving optional
 * secondary discovery paths. A partial unique index below guarantees that a
 * resource has at most one primary topic.
 */

create table public.resource_topic_links (
	resource_id bigint
		not null
		references public.safety_resources(id)
		on delete cascade,

	topic_id bigint
		not null
		references public.resource_topics(id)
		on delete restrict,

	is_primary boolean
		not null
		default false,

	sort_order smallint
		not null
		default 0,

	created_at timestamptz
		not null
		default now(),

	primary key (
		resource_id,
		topic_id
	),

	constraint resource_topic_links_sort_order_non_negative
		check (
			sort_order >= 0
		)
);


create unique index resource_topic_links_one_primary_idx
	on public.resource_topic_links (
		resource_id
	)
	where is_primary;


/* -------------------------------------------------------------------------
 * 5. RESOURCE-HAZARD RELATIONSHIPS
 * -------------------------------------------------------------------------
 *
 * A missing row means the resource is general preparedness content rather
 * than hazard-specific content.
 *
 * Many-to-many modelling prevents the same guidance from being duplicated
 * when it supports more than one reusable hazard.
 */

create table public.resource_hazards (
	resource_id bigint
		not null
		references public.safety_resources(id)
		on delete cascade,

	hazard_id bigint
		not null
		references public.hazards(id)
		on delete restrict,

	created_at timestamptz
		not null
		default now(),

	primary key (
		resource_id,
		hazard_id
	)
);


/* -------------------------------------------------------------------------
 * 6. OPTIONAL LOCATION APPLICABILITY
 * -------------------------------------------------------------------------
 *
 * A resource with no row here is not limited to a particular Saudi location.
 *
 * This relationship is deliberately separate from resource_hazards so future
 * content can be national, hazard-specific, location-specific, or both
 * without duplicating the resource body.
 */

create table public.resource_locations (
	resource_id bigint
		not null
		references public.safety_resources(id)
		on delete cascade,

	location_id bigint
		not null
		references public.locations(id)
		on delete restrict,

	created_at timestamptz
		not null
		default now(),

	primary key (
		resource_id,
		location_id
	)
);


/* -------------------------------------------------------------------------
 * 7. MISSION-TASK RESOURCE LINKS
 * -------------------------------------------------------------------------
 *
 * Mission tasks remain short and actionable.
 *
 * A linked primary resource supplies the fuller Resource Hub guidance.
 * Supporting resources may provide additional context or official references.
 */

create table public.mission_task_resources (
	task_id bigint
		not null
		references public.mission_tasks(id)
		on delete cascade,

	resource_id bigint
		not null
		references public.safety_resources(id)
		on delete cascade,

	link_role text
		not null
		default 'supporting',

	sort_order smallint
		not null
		default 0,

	created_at timestamptz
		not null
		default now(),

	primary key (
		task_id,
		resource_id
	),

	constraint mission_task_resources_link_role_valid
		check (
			link_role in (
				'primary',
				'supporting'
			)
		),

	constraint mission_task_resources_sort_order_non_negative
		check (
			sort_order >= 0
		)
);


create unique index mission_task_resources_one_primary_idx
	on public.mission_task_resources (
		task_id
	)
	where link_role = 'primary';


/* -------------------------------------------------------------------------
 * 8. QUIZ-QUESTION RESOURCE LINKS
 * -------------------------------------------------------------------------
 *
 * Quiz feedback can direct the learner to the same reviewed Resource Hub
 * content used by mission learning tasks instead of duplicating explanations.
 */

create table public.quiz_question_resources (
	question_id bigint
		not null
		references public.quiz_questions(id)
		on delete cascade,

	resource_id bigint
		not null
		references public.safety_resources(id)
		on delete cascade,

	link_role text
		not null
		default 'supporting',

	sort_order smallint
		not null
		default 0,

	created_at timestamptz
		not null
		default now(),

	primary key (
		question_id,
		resource_id
	),

	constraint quiz_question_resources_link_role_valid
		check (
			link_role in (
				'primary',
				'supporting'
			)
		),

	constraint quiz_question_resources_sort_order_non_negative
		check (
			sort_order >= 0
		)
);


create unique index quiz_question_resources_one_primary_idx
	on public.quiz_question_resources (
		question_id
	)
	where link_role = 'primary';


/* -------------------------------------------------------------------------
 * 9. DATABASE-CONTROLLED UPDATED_AT
 * ------------------------------------------------------------------------- */

create trigger on_resource_topic_updated
	before update
	on public.resource_topics
	for each row
	execute function private.set_updated_at();


create trigger on_safety_resource_updated
	before update
	on public.safety_resources
	for each row
	execute function private.set_updated_at();


create trigger on_resource_source_updated
	before update
	on public.resource_sources
	for each row
	execute function private.set_updated_at();


/* -------------------------------------------------------------------------
 * 10. INDEXES
 * -------------------------------------------------------------------------
 *
 * Primary keys already index their leading columns.
 *
 * Reverse relationship indexes support Resource Hub filtering and future
 * lookup paths from hazards, locations, missions, quizzes and resources.
 */

create index resource_topic_links_topic_id_idx
	on public.resource_topic_links (
		topic_id
	);


create index resource_hazards_hazard_id_idx
	on public.resource_hazards (
		hazard_id
	);


create index resource_locations_location_id_idx
	on public.resource_locations (
		location_id
	);


create index mission_task_resources_resource_id_idx
	on public.mission_task_resources (
		resource_id
	);


create index quiz_question_resources_resource_id_idx
	on public.quiz_question_resources (
		resource_id
	);


create index safety_resources_publication_sort_idx
	on public.safety_resources (
		publication_status,
		sort_order,
		id
	);


