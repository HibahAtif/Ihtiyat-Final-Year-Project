	enable row level security;


/* -------------------------------------------------------------------------
 * 12. CLIENT AND SERVICE-ROLE PRIVILEGES
 * -------------------------------------------------------------------------
 *
 * Resource Hub content is public safety information, so both guests and
 * authenticated users may read published rows.
 *
 * Curated content remains read-only to ordinary application clients.
 */

revoke all
	on table
		public.resource_topics,
		public.safety_resources,
		public.resource_sources,
		public.resource_topic_links,
		public.resource_hazards,
		public.resource_locations,
		public.mission_task_resources,
		public.quiz_question_resources
	from anon, authenticated;


grant select
	on table
		public.resource_topics,
		public.safety_resources,
		public.resource_sources,
		public.resource_topic_links,
		public.resource_hazards,
		public.resource_locations,
		public.mission_task_resources,
		public.quiz_question_resources
	to anon, authenticated;


grant select, insert, update, delete
	on table
		public.resource_topics,
		public.safety_resources,
		public.resource_sources,
		public.resource_topic_links,
		public.resource_hazards,
		public.resource_locations,
		public.mission_task_resources,
		public.quiz_question_resources
	to service_role;


/*
 * Identity sequences are never required by ordinary clients because curated
 * Resource Hub records cannot be created directly by the mobile application.
 */

revoke all
	on sequence
		public.resource_topics_id_seq,
		public.safety_resources_id_seq,
		public.resource_sources_id_seq
	from anon, authenticated;


grant usage, select
	on sequence
		public.resource_topics_id_seq,
		public.safety_resources_id_seq,
		public.resource_sources_id_seq
	to service_role;


/* -------------------------------------------------------------------------
 * 13. PUBLIC READ POLICIES
 * -------------------------------------------------------------------------
 *
 * Policies intentionally expose only active/published catalogue content.
 *
 * This differs from immutable reference catalogues such as locations:
 * draft and retired safety guidance must not be accidentally displayed to
 * users merely because the row exists in PostgreSQL.
 */

create policy "Application clients can read active resource topics"
	on public.resource_topics
	for select
	to anon, authenticated
	using (
		is_active
	);


create policy "Application clients can read published safety resources"
	on public.safety_resources
	for select
	to anon, authenticated
	using (
		publication_status = 'published'
	);


create policy "Application clients can read sources for published resources"
	on public.resource_sources
	for select
	to anon, authenticated
	using (
		is_active
		and exists (
			select 1
			from public.safety_resources as resource
			where resource.id = resource_id
				and resource.publication_status = 'published'
		)
	);


create policy "Application clients can read published resource topic links"
	on public.resource_topic_links
	for select
	to anon, authenticated
	using (
		exists (
			select 1
			from public.safety_resources as resource
			where resource.id = resource_id
				and resource.publication_status = 'published'
		)
		and exists (
			select 1
			from public.resource_topics as topic
			where topic.id = topic_id
				and topic.is_active
		)
	);


create policy "Application clients can read published resource hazard links"
	on public.resource_hazards
	for select
	to anon, authenticated
	using (
		exists (
			select 1
			from public.safety_resources as resource
			where resource.id = resource_id
				and resource.publication_status = 'published'
		)
		and exists (
			select 1
			from public.hazards as hazard
			where hazard.id = hazard_id
				and hazard.is_active
		)
	);


create policy "Application clients can read published resource location links"
	on public.resource_locations
	for select
	to anon, authenticated
	using (
		exists (
			select 1
			from public.safety_resources as resource
			where resource.id = resource_id
				and resource.publication_status = 'published'
		)
		and exists (
			select 1
			from public.locations as location
			where location.id = location_id
				and location.is_active
		)
	);


create policy "Application clients can read active mission resource links"
	on public.mission_task_resources
	for select
	to anon, authenticated
	using (
		exists (
			select 1
			from public.safety_resources as resource
			where resource.id = resource_id
				and resource.publication_status = 'published'
		)
		and exists (
			select 1
			from public.mission_tasks as task
			join public.preparedness_missions as mission
				on mission.id = task.mission_id
			left join public.hazards as hazard
				on hazard.id = task.hazard_id
			where task.id = task_id
				and task.is_active
				and mission.is_active
				and (
					task.hazard_id is null
					or hazard.is_active
				)
		)
	);


create policy "Application clients can read active quiz resource links"
	on public.quiz_question_resources
	for select
	to anon, authenticated
	using (
		exists (
			select 1
			from public.safety_resources as resource
			where resource.id = resource_id
				and resource.publication_status = 'published'
		)
		and exists (
			select 1
			from public.quiz_questions as question
			join public.preparedness_missions as mission
				on mission.id = question.mission_id
			left join public.hazards as hazard
				on hazard.id = question.hazard_id
			where question.id = question_id
				and question.is_active
				and mission.is_active
				and (
					question.hazard_id is null
					or hazard.is_active
				)
		)
	);


/* -------------------------------------------------------------------------
 * 14. SCHEMA DOCUMENTATION
 * ------------------------------------------------------------------------- */

comment on column public.safety_resources.last_reviewed_on is
	'Date on which the curated Ihtiyat resource was last reviewed against its cited sources.';

commit;
