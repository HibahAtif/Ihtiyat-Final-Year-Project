/*
 * Ihtiyat disaster preparedness engine.
 *
 * This migration introduces the relational foundation for:
 *
 * - reusable hazard definitions;
 * - location-to-hazard preparedness relevance;
 * - national and adaptive preparedness missions;
 * - official mission checklist tasks;
 * - quiz-based preparedness questions;
 * - private per-user task and quiz progress;
 * - private preparedness achievements.
 *
 * Location-hazard relevance is deliberately separate from alert severity.
 * A relevance rank controls preparedness-content prioritisation for a
 * location. It does not represent the severity of a current hazard event,
 * a forecast probability, or a scientific risk score.
 *
 * Curated preparedness catalogue tables are readable by application clients
 * but remain read-only to anon and authenticated roles.
 *
 * User progress and achievement records are private and protected by
 * Row Level Security.
 */

begin;


/* -------------------------------------------------------------------------
 * 1. HAZARD CATALOGUE
 * -------------------------------------------------------------------------
 *
 * Hazards are reusable entities and are not hard-coded to individual
 * locations. A hazard may therefore be associated with many locations and
 * may also remain available as general preparedness content when it is not
 * prioritised for the user's selected location.
 */

create table public.hazards (
	id bigint
		generated by default as identity
		primary key,

	code text
		not null
		unique,

	name_en text
		not null,

	name_ar text
		not null,

	classification text
		not null,

	sort_order smallint
		not null
		default 0,

	is_active boolean
		not null
		default true,

	created_at timestamptz
		not null
		default now(),

	constraint hazards_code_format
		check (
			code ~ '^[a-z0-9]+(_[a-z0-9]+)*$'
		),

	constraint hazards_name_en_length
		check (
			char_length(
				btrim(name_en)
			) between 1 and 120
		),

	constraint hazards_name_ar_length
		check (
			char_length(
				btrim(name_ar)
			) between 1 and 120
		),

	constraint hazards_classification_valid
		check (
			classification in (
				'core',
				'supported_regional',
				'resource_supported'
			)
		),

	constraint hazards_sort_order_non_negative
		check (
			sort_order >= 0
		)
);


/*
 * Connect curated locations to hazards that deserve additional
 * preparedness prominence for that location.
 *
 * Relevance ranks:
 *
 * 1 = highest preparedness relevance
 * 2 = secondary preparedness relevance
 * 3 = contextual preparedness relevance
 *
 * Absence from this table does NOT make a hazard unavailable.
 */
create table public.location_hazard_profiles (
	location_id bigint
		not null
		references public.locations(id)
		on delete restrict,

	hazard_id bigint
		not null
		references public.hazards(id)
		on delete restrict,

	relevance_rank smallint
		not null,

	is_active boolean
		not null
		default true,

	created_at timestamptz
		not null
		default now(),

	primary key (
		location_id,
		hazard_id
	),

	constraint location_hazard_profiles_relevance_rank_valid
		check (
			relevance_rank between 1 and 3
		)
);

comment on column
	public.location_hazard_profiles.relevance_rank
is
	'Preparedness-content relevance only. This is not alert severity, hazard probability, or a scientific risk score.';


