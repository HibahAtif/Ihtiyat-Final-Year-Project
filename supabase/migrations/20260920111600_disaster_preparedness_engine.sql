		user_id,
		task_id
	),

	constraint user_mission_task_progress_completion_consistent
		check (
			(
				is_completed = true
				and completed_at is not null
			)
			or
			(
				is_completed = false
				and completed_at is null
			)
		)
);


/*
 * Manage task completion timestamps inside PostgreSQL rather than trusting
 * client-provided timestamps.
 */
create or replace function private.set_task_progress_timestamps()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
	new.updated_at = now();

	if new.is_completed then
		if tg_op = 'INSERT'
			or old.is_completed = false
			or new.completed_at is null
		then
			new.completed_at = now();
		end if;
	else
		new.completed_at = null;
	end if;

	return new;
end;
$$;


create trigger on_user_mission_task_progress_changed
	before insert or update
	on public.user_mission_task_progress
	for each row
	execute function private.set_task_progress_timestamps();


/* -------------------------------------------------------------------------
 * 6. PRIVATE QUIZ PROGRESS
 * -------------------------------------------------------------------------
 *
 * The application records whether a user has successfully completed a
