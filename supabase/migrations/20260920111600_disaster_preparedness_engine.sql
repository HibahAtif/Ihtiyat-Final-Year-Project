 * rather than duplicated as stored totals.
 */

create table public.user_mission_task_progress (
	user_id uuid
		not null
		references auth.users(id)
		on delete cascade,

	task_id bigint
		not null
		references public.mission_tasks(id)
		on delete cascade,

	is_completed boolean
		not null
		default false,

	completed_at timestamptz,

	created_at timestamptz
		not null
		default now(),

	updated_at timestamptz
		not null
		default now(),

